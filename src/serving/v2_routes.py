"""
src/serving/v2_routes.py
------------------------
Additive endpoints for the adaptive-v2 upgrade. Registered on the existing
FastAPI app by inference_service.py (build_router(service_module)), so no
existing route, field or signature changes.

  GET  /session/{id}/profile   mastery / readiness profile (contract B)
  GET  /student/{id}/profile   same, for a student id
  GET  /class/overview?source=live|sample   teacher overview (contract C)
  POST /session/{id}/feedback  perceived difficulty + helpfulness (contract D)
"""

import re
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

from fastapi import APIRouter, HTTPException, status
from pydantic import BaseModel, Field

from serving.adaptive_session import TOPICS
from serving.mastery import build_profile
from serving.policy_config import RECOMMENDED_ACTIONS, get_config

SIM_PREFIX = "sim_"
SAMPLE_LABEL = "Simulated demo students (synthetic, generated by scripts/seed_demo_data.py)"


class FeedbackRequest(BaseModel):
    perceived: str = Field(..., pattern="^(too_easy|about_right|too_hard)$")
    helpful: Optional[int] = Field(default=None, ge=1, le=5)


class ProfileCache:
    """Per-student profile cache, invalidated whenever the student answers."""

    def __init__(self):
        self._store: Dict[str, Any] = {}

    def get(self, key: str, n_interactions: int):
        hit = self._store.get(key)
        if hit and hit[0] == n_interactions:
            return hit[1]
        return None

    def put(self, key: str, n_interactions: int, value):
        self._store[key] = (n_interactions, value)

    def invalidate_student(self, student_id: str):
        for k in [k for k in self._store if k.split("|", 1)[0] == student_id]:
            self._store.pop(k, None)


profile_cache = ProfileCache()


def _safe_predictor(svc):
    def predictor(history, candidates):
        return svc._predictor(history, candidates)
    return predictor


def student_profile(svc, student_id: str, session_id: Optional[str] = None,
                    use_cache: bool = True) -> Dict[str, Any]:
    """Profile from the student's cumulative history (same source as /session/{id}/predict)."""
    db = svc.session_manager.db
    full = db.get_full_history(student_id)
    if session_id is not None:
        if not full:
            full = db.get_session_interactions(session_id)
        sess_hist = db.get_session_interactions(session_id)
    else:
        last_sid = full[-1].get("session_id") if full else None
        sess_hist = [h for h in full if h.get("session_id") == last_sid] if last_sid else []
    key = f"{student_id}|{session_id or ''}"
    if use_cache:
        cached = profile_cache.get(key, len(full))
        if cached is not None:
            return cached
    prof = build_profile(
        full_history=full,
        topics=[{"raw_skill_id": t["raw_skill_id"], "skill_name": t["skill_name"]} for t in TOPICS],
        predictor=_safe_predictor(svc),
        session_history=sess_hist,
        session_id=session_id,
        student_id=student_id,
    )
    prof["n_interactions"] = len(full)
    if use_cache:
        profile_cache.put(key, len(full), prof)
    return prof


def list_students(svc, source: str) -> List[Dict[str, Any]]:
    """Students with at least one interaction, filtered by source.
    live   = source live/NULL, excluding EXCLUDE_STUDENT_REGEX and sim_ ids
    sample = simulated demo students (source 'sample' or sim_ prefix)"""
    cfg = get_config()
    with svc.session_manager.db._get_connection() as conn:
        rows = conn.execute(
            """SELECT s.student_id, s.source, COUNT(i.id) AS n
               FROM students s JOIN interactions i ON i.student_id = s.student_id
               GROUP BY s.student_id ORDER BY s.student_id"""
        ).fetchall()
    out = []
    for r in rows:
        sid, src = r["student_id"], (r["source"] or "live")
        is_sim = src == "sample" or sid.startswith(SIM_PREFIX)
        if source == "sample":
            if is_sim:
                out.append({"student_id": sid, "source": src, "n": int(r["n"])})
        else:
            if not is_sim and src == "live" and not cfg.is_excluded_student(sid):
                out.append({"student_id": sid, "source": src, "n": int(r["n"])})
    return out


def class_overview(svc, source: str = "live") -> Dict[str, Any]:
    names = {t["raw_skill_id"]: t["skill_name"] for t in TOPICS}
    students, counts, attention = [], {}, []
    for st in list_students(svc, source):
        prof = student_profile(svc, st["student_id"])
        topics = {}
        for t in prof["topics"]:
            topics[str(t["topic"])] = {"status": t["status"], "n_answers": t["n_answers"]}
            counts[t["status"]] = counts.get(t["status"], 0) + 1
            if t["status"] == "needs_support":
                attention.append({"student_id": st["student_id"], "topic": t["topic"],
                                  "skill_name": t["skill_name"], "status": t["status"],
                                  "n_answers": t["n_answers"], "recommended_action": t["recommended_action"]})
        students.append({"student_id": st["student_id"], "n_interactions": st["n"],
                         "profile_reliable": prof["profile_reliable"], "topics": topics})
    attention.sort(key=lambda a: (-a["n_answers"], a["student_id"]))
    return {
        "source": source,
        "label": SAMPLE_LABEL if source == "sample" else "Live students (test/smoke/simulated accounts excluded)",
        "skills": [{"skill_id": str(k), "name": v} for k, v in names.items()],
        "students": students,
        "status_counts": counts,
        "needs_attention": attention,
        "note": "Statuses are rule-based estimates; recommended actions are rule-based suggestions.",
    }


def build_router(svc) -> APIRouter:
    router = APIRouter()

    # Invalidate cached profiles when a new answer is stored.
    try:
        svc.adaptive_manager.on_answer = profile_cache.invalidate_student
    except Exception:
        pass

    @router.get("/session/{session_id}/profile")
    def api_session_profile(session_id: str):
        row = svc.session_manager.db.get_session(session_id)
        if not row:
            raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Session '{session_id}' not found")
        return student_profile(svc, row["student_id"], session_id=session_id)

    @router.get("/student/{student_id}/profile")
    def api_student_profile(student_id: str):
        return student_profile(svc, student_id.strip(), session_id=None)

    @router.get("/class/overview")
    def api_class_overview(source: str = "live"):
        source = (source or "live").lower()
        if source not in ("live", "sample"):
            raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="source must be 'live' or 'sample'")
        return class_overview(svc, source)

    @router.post("/session/{session_id}/feedback")
    def api_feedback(session_id: str, req: FeedbackRequest):
        row = svc.session_manager.db.get_session(session_id)
        if not row:
            raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Session '{session_id}' not found")
        policy = None
        mode = None
        sess = svc.adaptive_manager.sessions.get(session_id)
        if sess is not None:
            policy, mode = sess.policy, sess.session_mode
        event = {
            "event": "feedback",
            "session_id": session_id,
            "student_id": row["student_id"],
            "perceived": req.perceived,
            "helpful": req.helpful,
            "policy": policy,
            "session_mode": mode,
            "timestamp": datetime.now(timezone.utc).isoformat(),
        }
        svc._log_line(event)
        return {"ok": True, "event": event}

    return router
