"""
scripts/check_generator.py
--------------------------
Measures the parametric question generator (v3 Stage 8) and writes
reports/v3/generator_check.md / .csv.

Per topic and level (N items each, seed fixed): answer self-check pass rate,
distinct items out of N (how quickly the parameter space repeats), mean
`complexity` (digits + steps + used flags; ordered by construction), and a crude
SURFACE proxy that is not built in: the number of digit characters in the question
text. The proxy is reported as measured, including where it is not monotone.

Usage: python scripts/check_generator.py [--n 300] [--seed 2026]
"""

import argparse
import csv
import random
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from questions.generator import all_topic_keys, check_answer, generate  # noqa: E402
from serving.sections import SECTIONS  # noqa: E402

OUT = ROOT / "reports" / "v3"
LEVELS = ("easy", "medium", "hard")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=300)
    ap.add_argument("--seed", type=int, default=2026)
    args = ap.parse_args()
    print(f"[generator] seed = {args.seed}, n = {args.n} per topic x level")
    sec_of = {t["key"]: s for s, c in SECTIONS.items() for t in c["topics"]}
    rows, examples = [], {}
    for key in all_topic_keys():
        for lvl in LEVELS:
            rng = random.Random(args.seed)
            items = [generate(key, lvl, rng=rng) for _ in range(args.n)]
            ok = sum(check_answer(it["correct_answer"], it) for it in items)
            rows.append({"topic": key, "section": sec_of.get(key, "default topics"), "level": lvl, "n": args.n,
                         "self_check_pass": ok / args.n,
                         "distinct": len({it["question_text"] for it in items}),
                         "complexity_mean": sum(it["complexity"] for it in items) / args.n,
                         "digits_in_text_mean": sum(len(re.findall(r"\d", it["question_text"])) for it in items) / args.n,
                         "answer_types": ",".join(sorted({it["answer_type"] for it in items}))})
            examples[(key, lvl)] = items[0]
    OUT.mkdir(parents=True, exist_ok=True)
    with open(OUT / "generator_check.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        for r in rows:
            w.writerow({k: (round(v, 4) if isinstance(v, float) else v) for k, v in r.items()})
    by = {(r["topic"], r["level"]): r for r in rows}
    n_mono_c = n_mono_d = 0
    L = ["# Question generator check (Stage 8)", "",
         f"Generated by `python scripts/check_generator.py --n {args.n} --seed {args.seed}`. "
         f"{len(all_topic_keys())} topics x 3 levels x {args.n} items.", "",
         "| Topic | Section | Self-check pass (E/M/H) | Distinct of N (E/M/H) | Complexity mean (E/M/H) | "
         "Digits in text (E/M/H) | Answer types |", "|---|---|---|---|---|---|---|"]
    for key in all_topic_keys():
        e, m, h = (by[(key, l)] for l in LEVELS)
        mono_c = e["complexity_mean"] < m["complexity_mean"] < h["complexity_mean"]
        mono_d = e["digits_in_text_mean"] < m["digits_in_text_mean"] < h["digits_in_text_mean"]
        n_mono_c += mono_c
        n_mono_d += mono_d
        L.append(f"| {key} | {e['section']} | {e['self_check_pass']:.0%} / {m['self_check_pass']:.0%} / {h['self_check_pass']:.0%} | "
                 f"{e['distinct']} / {m['distinct']} / {h['distinct']} | "
                 f"{e['complexity_mean']:.1f} / {m['complexity_mean']:.1f} / {h['complexity_mean']:.1f} | "
                 f"{e['digits_in_text_mean']:.1f} / {m['digits_in_text_mean']:.1f} / {h['digits_in_text_mean']:.1f}"
                 f"{'' if mono_d else ' (not monotone)'} | {e['answer_types']}/{h['answer_types']} |")
    k = len(all_topic_keys())
    L += ["", f"- Complexity (by construction) is strictly ordered easy < medium < hard for {n_mono_c} of {k} topics.",
          f"- The independent surface proxy (digit characters in the text) is strictly ordered for {n_mono_d} of {k} "
          "topics. Where it is not, harder items use fewer but harder numbers (e.g. multiple-choice factorising, "
          "exponent rules), so this proxy is weak; it is NOT evidence about how hard students find the items.",
          "- 'Distinct of N' below N means the parameter space for that topic/level is small; the session engine "
          "still never repeats an item text within a session (it re-draws, and flags `repeated` if impossible).",
          "- None of this shows that the levels match real student difficulty: that needs logged answers "
          "(calibration) and a teacher review of the items (see docs/QUESTION_GENERATOR.md).", "",
          "## One example per topic and level", ""]
    for key in all_topic_keys():
        for lvl in LEVELS:
            it = examples[(key, lvl)]
            L.append(f"- `{key}` {lvl} (d={it['difficulty']}): {it['question_text']}  -> **{it['correct_answer']}**")
    L.append("")
    (OUT / "generator_check.md").write_text("\n".join(L), encoding="utf-8")
    print(f"[generator] complexity ordered {n_mono_c}/{k}; text proxy ordered {n_mono_d}/{k}; "
          "reports/v3/generator_check.md written")


if __name__ == "__main__":
    main()
