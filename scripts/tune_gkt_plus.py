"""
scripts/tune_gkt_plus.py
------------------------
Small hyper-parameter search for GatedKT+ on the ASSISTments VALIDATION split only
(seed 0; the test split is never scored here). Grid: dropout x weight decay; Adam lr
1e-3, up to --epochs epochs with early stopping (patience 3). The setting with the
highest validation AUC is written to reports/v3/gkt_plus_tuning.md / .json and is
then fixed for the benchmark (reports/v3/IMPROVED_PREREG.md).

Usage: python scripts/tune_gkt_plus.py [--epochs 12] [--workers 4]
"""

import argparse
import itertools
import json
import pickle
import sys
import time
from multiprocessing import get_context
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

OUT = ROOT / "reports" / "v3"
GRID = {"dropout": [0.1, 0.3], "weight_decay": [0.0, 1e-5]}


def _run(cfg):
    import warnings
    warnings.filterwarnings("ignore")
    import torch
    torch.set_num_threads(1)
    from baselines.deep import make_deep
    from baselines.ours import rt_stats_from_split
    with open(ROOT / "data" / "processed" / "windowed_data.pkl", "rb") as f:
        d = pickle.load(f)
    tr, va = d["splits"]["train"], d["splits"]["val"]
    t0 = time.time()
    m = make_deep("gkt_plus", int(d["num_skills"]), seed=0, epochs=cfg["epochs"], patience=3,
                  dropout=cfg["dropout"], weight_decay=cfg["weight_decay"], rt_stats=rt_stats_from_split(tr))
    m.fit(tr, va)
    return dict(cfg, best_val_auc=m.best_val_auc, epochs_run=len(m.history_log), minutes=round((time.time() - t0) / 60, 1))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--epochs", type=int, default=12)
    ap.add_argument("--workers", type=int, default=4)
    args = ap.parse_args()
    cfgs = [dict(zip(GRID, v), epochs=args.epochs) for v in itertools.product(*GRID.values())]
    print(f"[tune] seed 0, {len(cfgs)} settings, validation split only")
    with get_context("spawn").Pool(args.workers) as pool:
        res = pool.map(_run, cfgs)
    best = max(res, key=lambda r: r["best_val_auc"])
    (OUT / "gkt_plus_tuning.json").write_text(json.dumps({"results": res, "best": best}, indent=2), encoding="utf-8")
    L = ["# GatedKT+ hyper-parameter search (validation split only)", "",
         f"Generated by `python scripts/tune_gkt_plus.py --epochs {args.epochs}`. Seed 0, ASSISTments official split; "
         "selection by best validation AUC; the test split is not used.", "",
         "| dropout | weight decay | best val AUC | epochs run | minutes |", "|---|---|---|---|---|"]
    for r in sorted(res, key=lambda r: -r["best_val_auc"]):
        L.append(f"| {r['dropout']} | {r['weight_decay']:g} | {r['best_val_auc']:.4f} | {r['epochs_run']} | {r['minutes']} |")
    L += ["", f"**Selected: dropout {best['dropout']}, weight decay {best['weight_decay']:g}.**", ""]
    (OUT / "gkt_plus_tuning.md").write_text("\n".join(L), encoding="utf-8")
    print(f"[tune] selected dropout={best['dropout']} weight_decay={best['weight_decay']} val AUC {best['best_val_auc']:.4f}")


if __name__ == "__main__":
    main()
