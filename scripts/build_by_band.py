"""
scripts/build_by_band.py
------------------------
Per-grade-band test AUC (v3 Stage 6) for the main model and the baselines.

1. Reads the ASSISTments skill names from data/raw/skill_builder_data.csv (read-only)
   and writes data/processed_v3/skill_names_all.json (raw skill id -> name).
2. Assigns every skill a band with serving.sections.band_for_name (rule D34):
   primary / secondary / unassigned (no ASSISTments skill is undergraduate level).
3. Uses the cached Stage 5 test predictions (data/processed_v3/benchmark_preds/, written
   by scripts/benchmark_seeds.py deep) and groups each prediction by the band of its
   TARGET skill; reports AUC per band (mean and std over seeds) and the number of
   predictions per band.

Output: reports/v3/by_band.md, reports/v3/by_band.csv
Usage:  python scripts/build_by_band.py
"""

import csv
import json
import pickle
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
for p in (SRC, ROOT / "scripts"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

from baselines.base import auc, mean_ci, split_to_sequences  # noqa: E402
from serving.sections import band_for_name  # noqa: E402

RAW = ROOT / "data" / "raw" / "skill_builder_data.csv"
NAMES_OUT = ROOT / "data" / "processed_v3" / "skill_names_all.json"
OUT = ROOT / "reports" / "v3"
BANDS = ("primary", "secondary", "unassigned")


def skill_names():
    if NAMES_OUT.exists():
        return {int(k): v for k, v in json.loads(NAMES_OUT.read_text(encoding="utf-8")).items()}
    import pandas as pd
    df = pd.read_csv(RAW, encoding="ISO-8859-1", usecols=["skill_id", "skill_name"], low_memory=False).dropna()
    df = df[~df["skill_id"].astype(str).str.contains("_")]
    df["skill_id"] = df["skill_id"].astype(float).astype(int)
    names = {int(r.skill_id): str(r.skill_name).strip() for r in df.drop_duplicates("skill_id").itertuples()}
    NAMES_OUT.parent.mkdir(parents=True, exist_ok=True)
    NAMES_OUT.write_text(json.dumps(names, indent=1), encoding="utf-8")
    return names


def main():
    from benchmark_deep import PRED_DIR, _load_preds
    names = skill_names()
    with open(ROOT / "data" / "processed" / "windowed_data.pkl", "rb") as f:
        d = pickle.load(f)
    inv = {v: k for k, v in d["skill_map"].items()}          # internal -> raw
    band_of_skill = {i: band_for_name(names.get(int(inv[i]))) for i in inv}
    test = split_to_sequences(d["splits"]["test"])
    target_band = np.concatenate([[band_of_skill.get(int(k), "unassigned") for k in s["skill_seq"][1:]]
                                  for s in test if len(s["skill_seq"]) > 1])
    skills_per_band = {b: sorted(int(inv[i]) for i in inv if band_of_skill[i] == b) for b in BANDS}

    meta = json.loads((OUT / "stage5" / "benchmark_run_meta.json").read_text(encoding="utf-8"))
    preds = _load_preds(meta)
    rows = []
    for model, by_seed in preds.items():
        for b in BANDS:
            m = target_band == b
            vals = [auc(r["y"][m], r["p"][m]) for r in by_seed.values() if len(r["y"]) == len(target_band)]
            c = mean_ci(vals)
            rows.append({"model": model, "band": b, "n_predictions": int(m.sum()), "n_seeds": c["n"],
                         "auc_mean": c["mean"], "auc_std": c["std"], "ci_low": c["ci_low"], "ci_high": c["ci_high"]})
    with open(OUT / "by_band.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        for r in rows:
            w.writerow({k: (round(v, 6) if isinstance(v, float) else v) for k, v in r.items()})

    counts = {b: int((target_band == b).sum()) for b in BANDS}
    L = ["# Test AUC by grade band (Stage 6)", "",
         "Generated by `python scripts/build_by_band.py` from the cached Stage 5 test predictions "
         f"(official split, {len(meta['seeds'])} seeds, {meta['epochs']} epochs; v2 checkpoints: 3 seeds).", "",
         "Band of a prediction = band of its target skill. Bands come from the ASSISTments skill NAME "
         "(rule D34 in docs/DECISIONS.md, `serving.sections.band_for_name`): primary-level content by keyword, "
         "every other named skill secondary, unnamed skills unassigned. **No ASSISTments skill is undergraduate "
         "level, so there is no undergraduate row: the undergraduate section is not validated on real data.** "
         "The learners in ASSISTments 2009 were middle-school students, so the primary band measures "
         "primary-level CONTENT practised by older students, not primary-age learners.", "",
         "| Band | Skills | Test predictions |", "|---|---|---|"]
    for b in BANDS:
        L.append(f"| {b} | {len(skills_per_band[b])} | {counts[b]} |")
    L += ["", "| Model | primary AUC (mean ± std) | secondary AUC (mean ± std) | unassigned AUC (mean ± std) | seeds |",
          "|---|---|---|---|---|"]
    order = sorted(preds, key=lambda m: -np.mean([r["auc_mean"] for r in rows if r["model"] == m and r["band"] == "secondary"]))
    for mdl in order:
        cells = []
        for b in BANDS:
            r = next(r for r in rows if r["model"] == mdl and r["band"] == b)
            cells.append(f"{r['auc_mean']:.4f} ± {r['auc_std']:.4f}" if r["n_seeds"] else "n/a")
        n = next(r for r in rows if r["model"] == mdl)["n_seeds"]
        L.append(f"| {mdl} | " + " | ".join(cells) + f" | {n} |")
    L += ["", "Primary-band skills (raw ids): " + ", ".join(str(s) for s in skills_per_band["primary"]),
          "", "Unassigned skills have no name in the raw CSV (they appear only inside multi-skill rows).", ""]
    (OUT / "by_band.md").write_text("\n".join(L), encoding="utf-8")
    print("reports/v3/by_band.md written:", counts)


if __name__ == "__main__":
    main()
