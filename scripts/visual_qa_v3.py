"""
scripts/visual_qa_v3.py
-----------------------
v3 Stage 10 browser QA: starts the real services (FastAPI + Node) on a TEMPORARY DB
copy, optionally with demo.env, and runs scripts/visual_qa_v3.js in headless
Chrome/Edge for 1280 px and 375 px. Screenshots -> reports/v3/screenshots/,
summary -> reports/v3/ui_check.md. If no browser or puppeteer-core is available it
says so and exits with code 2 (the limitation is recorded, nothing is faked).

Usage: python scripts/visual_qa_v3.py [--env-file demo.env] [--sections primary,secondary]
"""

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common import PROJECT_ROOT, find_node  # noqa: E402
from _services import Services, temp_db_copy  # noqa: E402
from visual_qa import BROWSERS  # noqa: E402

OUT = PROJECT_ROOT / "reports" / "v3"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--env-file", default=None)
    ap.add_argument("--sections", default="primary,secondary")
    args = ap.parse_args()
    browser = next((b for b in BROWSERS if Path(b).exists()), None)
    shots = OUT / "screenshots"
    if not browser or not (PROJECT_ROOT / ".tools" / "qa" / "node_modules" / "puppeteer-core").exists():
        msg = "No Chrome/Edge or puppeteer-core found; browser screenshots were not taken (limitation recorded)."
        (OUT / "ui_check.md").write_text(f"# UI check (Stage 10)\n\n{msg}\n", encoding="utf-8")
        print(msg)
        return 2
    tmp = Path(tempfile.mkdtemp(prefix="kt_vqa3_"))
    env = {"KT_DB_PATH": str(temp_db_copy(tmp)), "KT_LOG_PATH": str(tmp / "logs.jsonl")}
    if args.env_file:
        from serving.policy_config import load_env_file
        env.update(load_env_file(PROJECT_ROOT / args.env_file))
    with Services(env, log_dir=tmp) as svc:
        r = subprocess.run([find_node(), str(PROJECT_ROOT / "scripts" / "visual_qa_v3.js"), svc.base, str(shots), browser,
                            args.sections], capture_output=True, text=True, encoding="utf-8")
    if r.returncode != 0:
        print(r.stderr[-3000:])
        return r.returncode
    res = json.loads((shots / "qa_v3_result.json").read_text(encoding="utf-8"))
    L = ["# UI check (Stage 10)", "",
         f"Generated by `python scripts/visual_qa_v3.py{' --env-file ' + args.env_file if args.env_file else ''} "
         f"--sections {args.sections}` in headless {Path(browser).stem} (real services, temporary DB copy).", "",
         "| Section | Width | Picker | Questions | MC items (buttons ok) | Section badge | Verdict shown during quiz | "
         "No horizontal overflow | Results banner |", "|---|---|---|---|---|---|---|---|---|"]
    ok = True
    for run in res["runs"]:
        good = run["picker"] and run["questions"] >= 10 and run["mc_buttons_ok"] and not run["verdict_leak"] \
            and run["overflow_ok"] and bool(run.get("results_banner") or not run["section"])
        ok = ok and good
        L.append(f"| {run['section'] or 'default'} | {run['width']} | {run['picker']} | {run['questions']} | "
                 f"{run['mc_items']} ({run['mc_buttons_ok']}) | {run.get('badge') or '-'} | {run['verdict_leak']} | "
                 f"{run['overflow_ok']} | {(run.get('results_banner') or '-')[:90]} |")
    L += ["", "| Dashboard width | Sections card | Labels | No horizontal overflow |", "|---|---|---|---|"]
    for w, d in res["dashboard"].items():
        ok = ok and d["card"] and d["overflow_ok"]
        L.append(f"| {w} | {d['card']} | {'; '.join(d['labels'])} | {d['overflow_ok']} |")
    L += ["", f"Console errors: {len(res['console_errors'])}" + (f" ({'; '.join(res['console_errors'][:3])})" if res["console_errors"] else ""),
          "", f"**Result: {'PASS' if ok else 'FAIL'}.** Screenshots: " + ", ".join(f"screenshots/{s}" for s in res["screenshots"]), ""]
    (OUT / "ui_check.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L[:12]))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
