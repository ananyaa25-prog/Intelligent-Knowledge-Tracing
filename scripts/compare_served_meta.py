"""
scripts/compare_served_meta.py
------------------------------
Demo rule (2) of reports/v3/META_PREREG.md: ASSISTments test AUC of the currently
served checkpoint (data/processed/best_full_gated.pt, read-only) and of the saved
seed-0 GatedKT+ meta checkpoint (models_v3/gkt_plus_meta_assist_seed0.pt), computed
the same way (next-step predictions over every real test position).

Usage: python scripts/compare_served_meta.py
Output: reports/v3/meta_serving_check.md / .json
"""

import json
import pickle
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
for p in (ROOT / "src", ROOT / "scripts"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

OUT = ROOT / "reports" / "v3"
META_PATH = ROOT / "models_v3" / "gkt_plus_meta_assist_seed0.pt"
SERVED_PATH = ROOT / "data" / "processed" / "best_full_gated.pt"


def main():
    import torch
    torch.manual_seed(0)
    from baselines.base import all_metrics
    from baselines.deep import make_deep
    from baselines.ours import OursVariant, rt_stats_from_split
    from benchmark_improved import tuned
    with open(ROOT / "data" / "processed" / "windowed_data.pkl", "rb") as f:
        d = pickle.load(f)
    tr, te, S = d["splits"]["train"], d["splits"]["test"], int(d["num_skills"])
    rts = rt_stats_from_split(tr)

    served = OursVariant.from_checkpoint("full_gated", 0, S, rts, path=SERVED_PATH)
    ps, ys, _ = served.predict_split(te)

    meta = make_deep("gkt_plus_meta", S, seed=0, rt_stats=rts, **tuned())
    meta._problem_index = np.load(META_PATH.with_suffix(".problems.npy"))
    meta.net = meta.build_net()
    meta.net.load_state_dict(torch.load(META_PATH, map_location="cpu"))
    meta.net.eval()
    pm, ym, _ = meta.predict_split(te)
    if not np.array_equal(ys, ym):
        raise SystemExit("prediction targets differ; comparison invalid")

    res = {"served_full_gated": all_metrics(ys, ps), "gkt_plus_meta_seed0": all_metrics(ym, pm)}
    passed = res["gkt_plus_meta_seed0"]["auc"] >= res["served_full_gated"]["auc"]
    res["rule2_passed"] = bool(passed)
    (OUT / "meta_serving_check.json").write_text(json.dumps(res, indent=2), encoding="utf-8")
    L = ["# Serving check: current checkpoint vs GatedKT+ meta (seed 0)", "",
         "Generated by `python scripts/compare_served_meta.py`. ASSISTments official test split, next-step "
         "predictions at every real position, same targets for both models. Demo rule (2) of "
         "reports/v3/META_PREREG.md.", "",
         "| Checkpoint | Test AUC | Brier | ECE |", "|---|---|---|---|"]
    for k, path in (("served_full_gated", SERVED_PATH), ("gkt_plus_meta_seed0", META_PATH)):
        m = res[k]
        L.append(f"| {path.relative_to(ROOT).as_posix()} | {m['auc']:.4f} | {m['brier']:.4f} | {m['ece']:.4f} |")
    L += ["", f"Rule (2) {'passed' if passed else 'not passed'}: GatedKT+ meta seed-0 test AUC "
          f"{'>=' if passed else '<'} served checkpoint test AUC.", ""]
    (OUT / "meta_serving_check.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
