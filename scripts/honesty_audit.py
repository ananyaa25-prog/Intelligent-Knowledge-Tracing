"""
scripts/honesty_audit.py
------------------------
v3 Stage 11 honesty audit of the documentation.

1. Forbidden-claim scan: README.md, docs/*.md and reports/v3/*.md are searched for
   wording such as "first", "novel", "state-of-the-art", "outperforms", "proves",
   "groundbreaking". Each hit is listed with its line; a hit is "ok" only when the
   line negates or quotes the claim (e.g. "No. ... not a new model", "No 'first'").
2. Number traceability: every number with >= 3 decimals (e.g. 0.8533, +0.0012) and
   every percentage with one decimal (e.g. 43.2%) in README.md and docs/*.md must
   appear in at least one generated source (reports/**, ADAPTIVE_KT_REPORT.md,
   data/processed/retrain.log). Signs are ignored.

Output: reports/v3/honesty_audit.md. Exit 1 if an unexplained claim or an untraceable
number remains.
Usage: python scripts/honesty_audit.py
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "reports" / "v3" / "honesty_audit.md"
DOCS = [ROOT / "README.md"] + sorted((ROOT / "docs").glob("*.md"))
CLAIM_FILES = DOCS + sorted((ROOT / "reports" / "v3").glob("*.md"))
FORBIDDEN = [r"\b(the|our|is the) first\b(?! (?:question|questions|answer|answers|two|2|session|seed|run|stage|time|commit|line|item|medium|attempt|attempts|try))",
             r"\bfirst (to|system|model|approach|method|work|tool|platform)\b",
             r"\bnovel\b", r"state[- ]of[- ]the[- ]art", r"\bSOTA\b", r"\boutperform", r"\bproves?\b",
             r"\bgroundbreaking\b", r"\brevolutionary\b", r"\bbest[- ]in[- ]class\b"]
NEGATION = re.compile(r"\b(no|not|never|nor|without|isn't|is not|does not|did not|cannot)\b|\"|'|`", re.I)
SOURCES = [p for p in (ROOT / "reports").rglob("*") if p.suffix in (".md", ".csv", ".json", ".log", ".txt")] + \
          [ROOT / "ADAPTIVE_KT_REPORT.md", ROOT / "data" / "processed" / "retrain.log"]
NUM = re.compile(r"(?<![\w.:])[+-]?(\d+\.\d{3,}|\d+\.\d%)")   # ':' excludes ids such as arXiv:2007.12061
SELF = {OUT}


def main():
    claim_hits, bad_claims = [], []
    for f in CLAIM_FILES:
        if f in SELF or not f.exists():
            continue
        for i, line in enumerate(f.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            for pat in FORBIDDEN:
                if re.search(pat, line, re.I):
                    ok = bool(NEGATION.search(line)) or line.strip().rstrip("*").endswith("?")   # a viva question
                    rec = (f.relative_to(ROOT).as_posix(), i, pat, line.strip()[:160], ok)
                    claim_hits.append(rec)
                    if not ok:
                        bad_claims.append(rec)
    corpus = "\n".join(p.read_text(encoding="utf-8", errors="replace") for p in SOURCES if p.exists() and p not in SELF)
    corpus_csv = corpus
    untraced, checked = [], 0
    for f in DOCS:
        for i, line in enumerate(f.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            for m in NUM.finditer(line):
                tok = m.group(1)
                checked += 1
                variants = {tok}
                if tok.endswith("%"):
                    v = float(tok[:-1]) / 100
                    variants |= {f"{v:.3f}", f"{v:.4f}"}
                else:
                    variants |= {tok.rstrip("0")} if "." in tok else set()
                if not any(v in corpus_csv for v in variants):
                    untraced.append((f.relative_to(ROOT).as_posix(), i, tok, line.strip()[:140]))
    L = ["# Honesty audit (v3 Stage 11)", "", "Generated by `python scripts/honesty_audit.py`.", "",
         f"## 1. Forbidden-claim scan ({len(claim_hits)} hits, {len(bad_claims)} not negated or quoted)", ""]
    if claim_hits:
        L += ["| File | Line | Pattern | Text | Negated / quoted |", "|---|---|---|---|---|"]
        for f, i, pat, txt, ok in claim_hits:
            L.append(f"| {f} | {i} | `{pat[:30]}` | {txt.replace('|', '/')} | {'yes' if ok else '**NO**'} |")
    L += ["", f"## 2. Number traceability ({checked} numbers checked, {len(untraced)} not found in any generated source)", ""]
    if untraced:
        L += ["| File | Line | Number | Text |", "|---|---|---|---|"]
        for f, i, tok, txt in untraced:
            L.append(f"| {f} | {i} | {tok} | {txt.replace('|', '/')} |")
    else:
        L.append("Every checked number appears in a generated source.")
    ok = not bad_claims and not untraced
    L += ["", f"**Result: {'PASS' if ok else 'FAIL'}.** Sources: reports/**, ADAPTIVE_KT_REPORT.md, data/processed/retrain.log.", ""]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"[audit] claims: {len(claim_hits)} hits, {len(bad_claims)} unexplained; numbers: {checked} checked, "
          f"{len(untraced)} untraced -> {'PASS' if ok else 'FAIL'}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
